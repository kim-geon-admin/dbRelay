CREATE TABLE SRC_USERS (
  USER_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  LOGIN_ID VARCHAR2(50 CHAR) NOT NULL,
  DISPLAY_NAME VARCHAR2(100 CHAR) NOT NULL,
  EMAIL VARCHAR2(254 CHAR) NOT NULL,
  USER_STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
  REGISTERED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SRC_USERS PRIMARY KEY (USER_ID),
  CONSTRAINT UQ_SRC_USERS_LOGIN UNIQUE (LOGIN_ID),
  CONSTRAINT UQ_SRC_USERS_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CK_SRC_USERS_STATUS CHECK (USER_STATUS IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);

CREATE TABLE SRC_USER_ADDRESSES (
  ADDRESS_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  USER_ID NUMBER(19) NOT NULL,
  ADDRESS_TYPE VARCHAR2(20 CHAR) NOT NULL,
  POSTAL_CODE VARCHAR2(20 CHAR) NOT NULL,
  CITY VARCHAR2(100 CHAR) NOT NULL,
  ADDRESS_LINE1 VARCHAR2(200 CHAR) NOT NULL,
  IS_PRIMARY CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SRC_USER_ADDRESSES PRIMARY KEY (ADDRESS_ID),
  CONSTRAINT FK_SRC_ADDR_USER FOREIGN KEY (USER_ID) REFERENCES SRC_USERS (USER_ID),
  CONSTRAINT CK_SRC_ADDR_PRIMARY CHECK (IS_PRIMARY IN ('Y', 'N'))
);

CREATE TABLE SRC_USER_CONTACT_EXPORT (
  CONTACT_EXPORT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  USER_ID NUMBER(19) NOT NULL,
  ADDRESS_ID NUMBER(19) NOT NULL,
  LOGIN_ID VARCHAR2(50 CHAR) NOT NULL,
  EMAIL VARCHAR2(254 CHAR) NOT NULL,
  ADDRESS_TYPE VARCHAR2(20 CHAR) NOT NULL,
  CITY VARCHAR2(100 CHAR) NOT NULL,
  POSTAL_CODE VARCHAR2(20 CHAR) NOT NULL,
  CONSTRAINT PK_SRC_USER_CONTACT_EXPORT PRIMARY KEY (CONTACT_EXPORT_ID)
);

