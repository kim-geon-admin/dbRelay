MERGE INTO TGT_USERS target
USING (
  SELECT USER_ID, LOGIN_ID, DISPLAY_NAME, EMAIL, USER_STATUS, REGISTERED_AT
  FROM SRC_USERS
  WHERE USER_ID BETWEEN 1001 AND 1003
) source
ON (target.USER_ID = source.USER_ID)
WHEN MATCHED THEN UPDATE SET
  target.LOGIN_ID = source.LOGIN_ID,
  target.DISPLAY_NAME = source.DISPLAY_NAME,
  target.EMAIL = source.EMAIL,
  target.USER_STATUS = source.USER_STATUS,
  target.REGISTERED_AT = source.REGISTERED_AT
WHEN NOT MATCHED THEN INSERT (USER_ID, LOGIN_ID, DISPLAY_NAME, EMAIL, USER_STATUS, REGISTERED_AT)
VALUES (source.USER_ID, source.LOGIN_ID, source.DISPLAY_NAME, source.EMAIL, source.USER_STATUS, source.REGISTERED_AT);

MERGE INTO TGT_USER_ADDRESSES target
USING (
  SELECT ADDRESS_ID, USER_ID, ADDRESS_TYPE, POSTAL_CODE, CITY, ADDRESS_LINE1, IS_PRIMARY, CREATED_AT
  FROM SRC_USER_ADDRESSES
  WHERE ADDRESS_ID BETWEEN 2001 AND 2003
) source
ON (target.ADDRESS_ID = source.ADDRESS_ID)
WHEN MATCHED THEN UPDATE SET
  target.USER_ID = source.USER_ID,
  target.ADDRESS_TYPE = source.ADDRESS_TYPE,
  target.POSTAL_CODE = source.POSTAL_CODE,
  target.CITY = source.CITY,
  target.ADDRESS_LINE1 = source.ADDRESS_LINE1,
  target.IS_PRIMARY = source.IS_PRIMARY,
  target.CREATED_AT = source.CREATED_AT
WHEN NOT MATCHED THEN INSERT (ADDRESS_ID, USER_ID, ADDRESS_TYPE, POSTAL_CODE, CITY, ADDRESS_LINE1, IS_PRIMARY, CREATED_AT)
VALUES (source.ADDRESS_ID, source.USER_ID, source.ADDRESS_TYPE, source.POSTAL_CODE, source.CITY, source.ADDRESS_LINE1, source.IS_PRIMARY, source.CREATED_AT);

MERGE INTO TGT_USER_CONTACT_EXPORT target
USING (
  SELECT CONTACT_EXPORT_ID, USER_ID, ADDRESS_ID, LOGIN_ID, EMAIL, ADDRESS_TYPE, CITY, POSTAL_CODE
  FROM SRC_USER_CONTACT_EXPORT
  WHERE CONTACT_EXPORT_ID BETWEEN 3001 AND 3003
) source
ON (target.CONTACT_EXPORT_ID = source.CONTACT_EXPORT_ID)
WHEN MATCHED THEN UPDATE SET
  target.USER_ID = source.USER_ID,
  target.ADDRESS_ID = source.ADDRESS_ID,
  target.LOGIN_ID = source.LOGIN_ID,
  target.EMAIL = source.EMAIL,
  target.ADDRESS_TYPE = source.ADDRESS_TYPE,
  target.CITY = source.CITY,
  target.POSTAL_CODE = source.POSTAL_CODE
WHEN NOT MATCHED THEN INSERT (CONTACT_EXPORT_ID, USER_ID, ADDRESS_ID, LOGIN_ID, EMAIL, ADDRESS_TYPE, CITY, POSTAL_CODE)
VALUES (source.CONTACT_EXPORT_ID, source.USER_ID, source.ADDRESS_ID, source.LOGIN_ID, source.EMAIL, source.ADDRESS_TYPE, source.CITY, source.POSTAL_CODE);

COMMIT;
